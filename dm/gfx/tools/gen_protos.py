#!/usr/bin/env python3
# Generate the host-side signature check table nvn_protos.h from the PFNNVN*PROC prototypes in nvn.h.
# Difference between Apple arm64 and Switch AAPCS64: for integer arguments narrower than 32 bits, Apple requires the caller to extend them and Switch does not ⇒
#   NVNboolean parameters are always replaced with uint32_t in the host signature (the implementation only looks at the low 8 bits); any other <32-bit parameter is reported as a failure on sight.
# Stack-passed arguments (>8 integer or >8 floating-point parameters) are packed differently on the two sides ⇒ reported a failure on sight.
# Usage: gen_protos.py <nvn.h> <name table (one per line, in load order)> <output .h>
#        gen_protos.py --elf <name table> <output .S>: the trampolines alone, in ELF spelling (Android, dm/android/cmake); the headers above do not depend on the object format
import re, sys

# Counting trampolines: one static assembly entry _nvnth_<i> per name, which atomically increments nvn_slot[i].cnt and then jumps to nvn_slot[i].fn.
# No code is generated at runtime (iOS has no JIT); x16/x17 are intra-procedure-call scratch registers, so the trampoline may use them freely.
# On entry to the target, x16 still points to this slot: the unimplemented stub nvn_unimpl_entry uses it to look the name back up.
# ELF: no _ prefix on C names, :lo12: page offsets, function symbol types and sizes, nvn_slot hidden (bound inside the image: libdmhost.so links with no text relocations),
# strings in a mergeable .rodata section under assembler-local .L labels
def thunks(names, elf=False):
    sym = (lambda x: x) if elf else (lambda x: '_' + x)
    page, pageoff, lab = ('nvn_slot', ':lo12:nvn_slot', '.Ln') if elf else ('_nvn_slot@PAGE', '_nvn_slot@PAGEOFF', 'Ln')
    S = ['// Generated by dm/gfx/tools/gen_protos.py; do not edit.',
         "// Counting uses the LSE atomic stadd (ARMv8.1; every Apple chip since A12 / M1 has it): the next line keeps this file independent of the compiler's -mcpu baseline.",
         '    .arch_extension lse'] + (['    .hidden nvn_slot'] if elf else []) + ['    .text', '    .p2align 2']
    for i, n in enumerate(names):
        S += [f'    .globl {sym(f"nvnth_{i}")}'] + ([f'    .type nvnth_{i}, %function'] if elf else []) + [f'{sym(f"nvnth_{i}")}:',
              f'    adrp x16, {page}', f'    add x16, x16, {pageoff}',
              f'    mov x17, #{i * 16}', '    add x16, x16, x17',
              '    mov x17, #1', '    stadd x17, [x16]', '    ldr x17, [x16, #8]', '    br x17'] + ([f'    .size nvnth_{i}, . - nvnth_{i}'] if elf else [])
    S += ['    .data', '    .p2align 3', f'    .globl {sym("nvn_thunk")}', f'{sym("nvn_thunk")}:'] + [f'    .quad {sym(f"nvnth_{i}")}' for i in range(len(names))]
    S += [f'    .globl {sym("nvn_names")}', f'{sym("nvn_names")}:'] + [f'    .quad {lab}{i}' for i in range(len(names))]
    S += ['    .section .rodata.str1.1,"aMS",@progbits,1' if elf else '    .cstring'] + [f'{lab}{i}: .asciz "{n}"' for i, n in enumerate(names)]
    return '\n'.join(S) + '\n'

if sys.argv[1] == '--elf':
    open(sys.argv[3], 'w').write(thunks([l.strip() for l in open(sys.argv[2]) if l.strip()], elf=True))
    sys.exit(0)

hdr, names_path, out = sys.argv[1:4]
src = open(hdr).read()
protos = {}
for m in re.finditer(r'typedef\s+([\w\s\*]+?)\s*\(\*PFNNVN(\w+)PROC\)\s*\(([^;]*?)\);', src, re.S):
    ret, key, args = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
    protos[key] = (ret, [a.strip() for a in args.split(',')] if args.strip() not in ('', 'void') else [])

FP = re.compile(r'^(const\s+)?(float|double)$')
SMALL = re.compile(r'^(const\s+)?(uint8_t|int8_t|uint16_t|int16_t|char|unsigned char|short|unsigned short|bool)$')
names = [l.strip() for l in open(names_path) if l.strip()]
lines = ['// Generated by dm/gfx/tools/gen_protos.py; do not edit. NVNboolean parameters are replaced with uint32_t.', '#pragma once', '#include "nvn.h"', '']
red, missing = [], []
for n in names:
    key = n[3:].upper()
    if key not in protos:
        missing.append(n)
        continue
    ret, args = protos[key]
    gp = fp = 0
    conv = []
    for a in args:
        t = re.sub(r'\s+\w+$', '', a) if not a.endswith('*') and len(a.split()) > 1 and a.split()[-1] not in ('int', 'float', 'double', 'char') and not a.split()[-1].endswith('_t') and not a.split()[-1].startswith(('NVN', 'PFN')) else a
        t = t.strip()
        if FP.match(t): fp += 1
        else: gp += 1
        if t == 'NVNboolean': t = 'uint32_t'
        elif SMALL.match(t): red.append(f'{n}: <32-bit argument {t}')
        conv.append(t)
    if gp > 8 or fp > 8: red.append(f'{n}: arguments on the stack gp={gp} fp={fp}')
    lines.append(f'typedef {ret} (*NVNT_{n})({", ".join(conv) if conv else "void"});')
lines.append('')
lines.append('// Names without a prototype in the header (newer interfaces): they can only get named stubs')
for n in missing: lines.append(f'//   {n}')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'prototypes {len(names) - len(missing)} / names {len(names)}; without a prototype {len(missing)}; [RED] {len(red)}')
for r in red: print('  [RED]', r)

th = out.replace('nvn_protos.h', 'nvn_thunks.S')
open(th, 'w').write(thunks(names))
hn = out.replace('nvn_protos.h', 'nvn_count.h')
open(hn, 'w').write('// Generated by gen_protos.py\n#pragma once\n#define NVN_NFUNC %d\n' % len(names))
