#!/bin/bash
# Regenerates present_spv.h (committed, so neither build needs a shader compiler) from present.vert / present.frag beside this script: glslangValidator (Homebrew), checked with spirv-val.
# Run it after editing either shader. Vulkan 1.1 SPIR-V (1.3): every target here takes it
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
GLSLANG=${GLSLANG:-/opt/homebrew/bin/glslangValidator}
SPIRV_VAL=${SPIRV_VAL:-/opt/homebrew/bin/spirv-val}
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
OUT=$HERE/../present_spv.h
for s in vert frag; do
    "$GLSLANG" -V --target-env vulkan1.1 -o "$W/$s.spv" "$HERE/present.$s" | { grep -v "^/" || true; }
    "$SPIRV_VAL" --target-env vulkan1.1 "$W/$s.spv"
    "$GLSLANG" -V --target-env vulkan1.1 --vn "present_${s}_spv" -o "$W/$s.h" "$HERE/present.$s" | { grep -v "^/" || true; }
done
{ echo "// Generated by kernels/gen_spv.sh from kernels/present.vert and present.frag: do not edit"
  echo "#pragma once"
  grep -vhE '^[[:space:]]*(//|#pragma once)' "$W/vert.h" "$W/frag.h"; } > "$OUT"
echo "wrote $OUT"
