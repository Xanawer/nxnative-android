#!/bin/bash
# Regenerates ../t_vkn_spv.h (committed, so the test needs no shader compiler) from the shaders beside this script: glslangValidator (Homebrew), checked with spirv-val, as dm/gfx/vkn/kernels/gen_spv.sh.
# Vulkan 1.1 SPIR-V (1.3). Run it after editing a shader
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
GLSLANG=${GLSLANG:-/opt/homebrew/bin/glslangValidator}
SPIRV_VAL=${SPIRV_VAL:-/opt/homebrew/bin/spirv-val}
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
OUT=$HERE/../t_vkn_spv.h
NAMES="t_vs.vert t_vs_ubo.vert t_ps.frag t_ps_tex.frag t_ps_utex.frag t_ps_interp.frag t_ps_o1.frag t_ps_in2.frag t_ps_arr.frag t_vs_int.vert t_ps_int.frag t_vs_va.vert t_vs_o2.vert t_ps_va.frag t_ps_idx.frag"
for s in $NAMES; do
    v=$(echo "$s" | tr . _)_spv
    "$GLSLANG" -V --target-env vulkan1.1 -o "$W/$s.spv" "$HERE/$s" | { grep -v "^/" || true; }
    "$SPIRV_VAL" --target-env vulkan1.1 "$W/$s.spv"
    "$GLSLANG" -V --target-env vulkan1.1 --vn "$v" -o "$W/$s.h" "$HERE/$s" | { grep -v "^/" || true; }
done
{ echo "// Generated by vkn_kernels/gen_spv.sh from the shaders there: do not edit"
  echo "#pragma once"
  for s in $NAMES; do grep -vhE '^[[:space:]]*(//|#pragma once)' "$W/$s.h"; done; } > "$OUT"
echo "wrote $OUT"
